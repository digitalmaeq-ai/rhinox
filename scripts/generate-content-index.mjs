/**
 * Auto-discovers every content module under content/** and writes
 * lib/content-items.generated.ts, so adding a new content ITEM never
 * requires editing lib/content.ts by hand.
 *
 * Usage:
 *   node scripts/generate-content-index.mjs
 *
 * Wired into package.json:
 *   "content:index": "node scripts/generate-content-index.mjs"
 *   "predev":        runs this automatically before `next dev`
 *   "prebuild":      runs this automatically before `next build`
 *
 * To add content: drop a .ts file under content/** exporting one or more
 * objects shaped like a ContentItem (needs id, slug, contentType, title —
 * anything else is picked up by whichever type it claims). No changes to
 * lib/content.ts, the registry, or any route are required for a new item
 * of an existing content type.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const contentDir = path.join(root, "content");
const outFile = path.join(root, "lib", "content-items.generated.ts");

// Retired content: kept on disk but never indexed, so it cannot appear
// anywhere on the site. Delete the files whenever convenient.
const RETIRED = /(^|[\\/])water-cycle[^\\/]*\.ts$/;

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) {
    return files;
  }

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      // Skip private/example folders (content/_examples, dotfolders) —
      // never treated as real content.
      if (entry.name.startsWith("_") || entry.name.startsWith(".")) {
        continue;
      }
      walk(full, files);
    } else if (
      entry.isFile() &&
      entry.name.endsWith(".ts") &&
      !entry.name.endsWith(".d.ts") &&
      !RETIRED.test(full)
    ) {
      files.push(full);
    }
  }

  return files;
}

function toImportPath(absoluteFile) {
  const rel = path
    .relative(contentDir, absoluteFile)
    .replace(/\\/g, "/");
  return `@/content/${rel.replace(/\.ts$/, "")}`;
}

function toSafeIdent(absoluteFile) {
  const rel = path
    .relative(contentDir, absoluteFile)
    .replace(/\\/g, "/");
  return (
    "c_" +
    rel
      .replace(/\.ts$/, "")
      .replace(/[^a-zA-Z0-9]/g, "_")
      .replace(/_+/g, "_")
  );
}

const files = walk(contentDir).sort();

if (files.length === 0) {
  console.warn("[content:index] No content files found under content/");
}

const imports = files.map((file) => {
  const ident = toSafeIdent(file);
  const importPath = toImportPath(file);
  return `import * as ${ident} from "${importPath}";`;
});

const spreads = files.map((file) => {
  const ident = toSafeIdent(file);
  return `  ...collect(${ident}),`;
});

const header = `/**
 * AUTO-GENERATED by scripts/generate-content-index.mjs — do not edit.
 * Run \`npm run content:index\` to regenerate (also runs on predev/prebuild).
 * Generated: ${new Date().toISOString()}
 * Source files: ${files.length}
 */

import type { ContentItem } from "./content-item-types";

function isContentItem(value: unknown): value is ContentItem {
  if (!value || typeof value !== "object") {
    return false;
  }

  const v = value as Record<string, unknown>;

  return (
    typeof v.id === "string" &&
    typeof v.slug === "string" &&
    typeof v.contentType === "string" &&
    typeof v.title === "string"
  );
}

function collect(mod: Record<string, unknown>): ContentItem[] {
  return Object.values(mod).filter(isContentItem);
}
`;

const body = `${imports.join("\n")}

export const generatedContentItems: ContentItem[] = [
${spreads.join("\n")}
];
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${header}\n${body}`, "utf8");

console.log(
  `[content:index] Wrote ${files.length} module(s) -> lib/content-items.generated.ts`
);

for (const file of files) {
  console.log(`  - ${path.relative(root, file)}`);
}

import "./copy-code-studio-assets.mjs";
